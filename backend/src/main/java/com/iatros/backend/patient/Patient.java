package com.iatros.backend.patient;

import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

import com.iatros.backend.shared.persistence.AuditedEntity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;

/** Patient identity and contact information. Clinical data lives in the medical record. */
@Entity
@Table(name = "patient")
public class Patient extends AuditedEntity {

	@Column(name = "clinic_id", nullable = false, updatable = false)
	private UUID clinicId;

	@Column(name = "first_name", nullable = false, length = 100)
	private String firstName;

	@Column(name = "last_name", nullable = false, length = 100)
	private String lastName;

	@Column(name = "date_of_birth", nullable = false)
	private LocalDate dateOfBirth;

	@Enumerated(EnumType.STRING)
	@Column(length = 20)
	private Gender gender;

	@Column(length = 40)
	private String phone;

	@Column(columnDefinition = "citext")
	private String email;

	@Column(length = 500)
	private String address;

	@Column(name = "emergency_contact_name", length = 200)
	private String emergencyContactName;

	@Column(name = "emergency_contact_phone", length = 40)
	private String emergencyContactPhone;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false, length = 20)
	private PatientStatus status = PatientStatus.ACTIVE;

	@Column(name = "archived_at")
	private Instant archivedAt;

	/** Generated by the database; used for trigram search. */
	@Column(name = "search_text", insertable = false, updatable = false)
	private String searchText;

	@Column(name = "created_by", updatable = false)
	private UUID createdBy;

	@Column(name = "updated_by")
	private UUID updatedBy;

	protected Patient() {
	}

	public Patient(UUID clinicId, String firstName, String lastName, LocalDate dateOfBirth, UUID createdBy) {
		this.clinicId = clinicId;
		this.firstName = firstName;
		this.lastName = lastName;
		this.dateOfBirth = dateOfBirth;
		this.createdBy = createdBy;
	}

	public void updateIdentity(String firstName, String lastName, LocalDate dateOfBirth, Gender gender, UUID updatedBy) {
		this.firstName = firstName;
		this.lastName = lastName;
		this.dateOfBirth = dateOfBirth;
		this.gender = gender;
		this.updatedBy = updatedBy;
	}

	public void updateContact(String phone, String email, String address, String emergencyContactName,
			String emergencyContactPhone, UUID updatedBy) {
		this.phone = phone;
		this.email = email;
		this.address = address;
		this.emergencyContactName = emergencyContactName;
		this.emergencyContactPhone = emergencyContactPhone;
		this.updatedBy = updatedBy;
	}

	public void archive(Instant at, UUID by) {
		this.status = PatientStatus.ARCHIVED;
		this.archivedAt = at;
		this.updatedBy = by;
	}

	public void restore(UUID by) {
		this.status = PatientStatus.ACTIVE;
		this.archivedAt = null;
		this.updatedBy = by;
	}

	public UUID getClinicId() {
		return clinicId;
	}

	public String getFirstName() {
		return firstName;
	}

	public String getLastName() {
		return lastName;
	}

	public LocalDate getDateOfBirth() {
		return dateOfBirth;
	}

	public Gender getGender() {
		return gender;
	}

	public String getPhone() {
		return phone;
	}

	public String getEmail() {
		return email;
	}

	public String getAddress() {
		return address;
	}

	public String getEmergencyContactName() {
		return emergencyContactName;
	}

	public String getEmergencyContactPhone() {
		return emergencyContactPhone;
	}

	public PatientStatus getStatus() {
		return status;
	}

	public Instant getArchivedAt() {
		return archivedAt;
	}

	public UUID getCreatedBy() {
		return createdBy;
	}

	public UUID getUpdatedBy() {
		return updatedBy;
	}

}
